<#
.SYNOPSIS
    Compiles the font key into the app for this build only.

    Reads the base64 key from $env:MASHHAD_FONT_KEY (the CI secret) and writes
    src/Mashhad.App/Generated/FontKey.g.cs, holding the key split and masked with random bytes
    (it never appears in source control). With -Remove, deletes that file again. Prints nothing
    about the key itself.
#>
param([switch]$Remove)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root 'src\Mashhad.App\Generated'
$file = Join-Path $dir 'FontKey.g.cs'

if ($Remove) { Remove-Item $dir -Recurse -Force -ErrorAction SilentlyContinue; return }

if ([string]::IsNullOrWhiteSpace($env:MASHHAD_FONT_KEY)) {
    Write-Host 'MASHHAD_FONT_KEY is not set: building without the Thmanyah Sans font (Segoe UI Variable is used).'
    Remove-Item $dir -Recurse -Force -ErrorAction SilentlyContinue
    return
}
try { $key = [Convert]::FromBase64String($env:MASHHAD_FONT_KEY.Trim()) } catch { throw 'MASHHAD_FONT_KEY is not valid base64.' }
if ($key.Length -ne 32) { throw 'MASHHAD_FONT_KEY must decode to 32 bytes.' }

# key[i] = a[(i*13+5) & 31] ^ b[i] ^ (0xA7 + i*29); a and b are random per build.
$b = [byte[]]::new(32); [System.Security.Cryptography.RandomNumberGenerator]::Fill($b)
$a = [byte[]]::new(32)
for ($i = 0; $i -lt 32; $i++) {
    $a[(($i * 13) + 5) -band 31] = $key[$i] -bxor $b[$i] -bxor ((0xA7 + $i * 29) -band 0xFF)
}
[Array]::Clear($key, 0, $key.Length)
$fmt = { param($bytes) ($bytes | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ' }

New-Item -ItemType Directory -Force $dir | Out-Null
@"
// <auto-generated> by scripts/embed-font-key.ps1 for one build. Never commit. </auto-generated>
namespace Mashhad.App.Fonts;

internal static partial class FontKeySource
{
    private static readonly byte[] A = { $(& $fmt $a) };
    private static readonly byte[] B = { $(& $fmt $b) };

    static partial void Load(ref byte[]? key)
    {
        var k = new byte[32];
        for (int i = 0; i < 32; i++) k[i] = (byte)(A[(i * 13 + 5) & 31] ^ B[i] ^ (byte)(0xA7 + i * 29));
        key = k;
    }
}
"@ | Set-Content -Path $file -Encoding utf8
Write-Host 'Font key compiled in for this build.'
